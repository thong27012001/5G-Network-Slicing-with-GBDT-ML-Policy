from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

from organize_pipeline_outputs import organize_pipeline_outputs
from tools.export_sla_kpi_plots import (
    SCENARIO_DELAY_TOLERANCE_MS,
    export_for_run,
    p95_targets_for_scenario,
    thresholds_for_scenario,
)


SCENARIOS = {
    "light": {
        "config": "slicesim/scenario-light.yml",
        "sla": "sla_reference_light.csv",
        "description": "Light high-activity 5G slicing workload",
    },
    "heavy": {
        "config": "slicesim/scenario-heavy.yml",
        "sla": "sla_reference_heavy.csv",
        "description": "Heavy high-activity 5G slicing workload",
    },
}

DEFAULT_MODEL_DIR = "models/sla_risk_gbdt"
DEFAULT_CONTROLLER_PRESET = "balanced_ml_v3_gentle"
DEFAULT_BROKER_PRESET = "forecasting_balanced"
LEGACY_OUTPUT_ARCHIVE_DIR = "FINAL_OUTPUT_#1"


def _repo_root() -> Path:
    return Path(__file__).resolve().parent


def _timestamp() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _resolve_output_root(path_value: str, repo_root: Path) -> Path:
    """Return the parent directory where FINAL_OUTPUT_* folders are created.

    FINAL_OUTPUT_#1 is an archived/reference output folder. New runs should be
    created next to it, not inside it, so report folders remain easy to compare.
    """
    output_root = Path(path_value)
    if not output_root.is_absolute():
        output_root = repo_root / output_root
    output_root = output_root.resolve()

    if output_root.name == LEGACY_OUTPUT_ARCHIVE_DIR:
        corrected = output_root.parent
        print(
            f"[warn] {LEGACY_OUTPUT_ARCHIVE_DIR} is an archive folder. "
            f"New FINAL_OUTPUT_* folders will be created next to it: {corrected}"
        )
        return corrected

    return output_root


def _select_scenario(cli_value: str | None) -> str:
    if cli_value:
        return cli_value

    print("Select a scenario:")
    for index, (name, config) in enumerate(SCENARIOS.items(), start=1):
        print(f"  {index}. {name} - {config['description']}")

    while True:
        value = input("Enter 1/2 or scenario name [light]: ").strip() or "light"
        if value in SCENARIOS:
            return value
        if value.isdigit():
            index = int(value)
            names = list(SCENARIOS)
            if 1 <= index <= len(names):
                return names[index - 1]
        print("Invalid scenario. Choose 'light' or 'heavy'.")


def _parse_seed_list(text: str) -> list[int] | None:
    tokens = [tok for tok in text.replace(",", " ").split() if tok]
    if not tokens:
        return None
    try:
        return [int(tok) for tok in tokens]
    except ValueError:
        return None


def _select_seeds(cli_value: list[int] | None) -> list[int]:
    if cli_value:
        return cli_value

    print("\nSelect seed(s) for simulation:")
    print("  - Single seed: e.g. '42'")
    print("  - Multi-seed (mean +/- std): e.g. '7 42 123' or '7,42,123'")
    print("  - Blank for default '42'")

    while True:
        raw = input("Enter seed(s) [42]: ").strip() or "42"
        seeds = _parse_seed_list(raw)
        if seeds:
            return seeds
        print("Invalid seed list. Use integers separated by space or comma.")


def _generate_sla_hit_outputs(output_dir: Path, scenario: str) -> None:
    export_for_run(
        output_dir,
        SCENARIO_DELAY_TOLERANCE_MS.copy(),
        "scenario_yaml",
        completion_thresholds=thresholds_for_scenario(scenario),
        p95_sla_targets=p95_targets_for_scenario(scenario),
    )


def _copy_map_shortcuts(output_dir: Path) -> None:
    shortcuts = {
        output_dir / "baseline_run" / "baseline_simulation.png": output_dir / "baseline_simulation_map.png",
        output_dir / "ml_run" / "ml_policy_simulation.png": output_dir / "ml_policy_simulation_map.png",
        output_dir / "baseline_run" / "output.txt": output_dir / "baseline_output.txt",
        output_dir / "ml_run" / "output.txt": output_dir / "ml_policy_output.txt",
    }
    for source, target in shortcuts.items():
        if source.exists():
            shutil.copy2(source, target)


def _write_run_summary(output_dir: Path, scenario: str, command: list[str]) -> None:
    text = [
        f"# Experiment Output: {scenario}",
        "",
        "This standardized folder was generated by `run_experiment.py`.",
        "",
        "## Command",
        "",
        "```text",
        " ".join(command),
        "```",
        "",
        "## Key files",
        "",
        "- `01_output_simulation/`: raw baseline and ML simulation CSV outputs.",
        "- `02_model_training_report_plot/`: model artifact summary copied from the model directory.",
        "- `03_KPI_plot_output_with_baseline/`: baseline-only KPI tables and raw files.",
        "- `04_KPI_plot_output_with_ML_Policy/`: ML-policy KPI/action/prediction files.",
        "- `05_KPI_plot_output_comparison/`: baseline-vs-ML CSV/PNG comparison artifacts.",
        "- `06_tradeoff_discussion_report/`: generated trade-off discussion report.",
        "- `../07_Model Report/`: global GBDT model report shared by all simulation seeds.",
        "",
    ]
    (output_dir / "RUN_SUMMARY.md").write_text("\n".join(text), encoding="utf-8")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Run baseline vs ML policy simulation for one release scenario.")
    parser.add_argument("--scenario", choices=sorted(SCENARIOS), help="Scenario to run. If omitted, prompts interactively.")
    parser.add_argument(
        "--seed",
        type=int,
        nargs="+",
        default=None,
        help=(
            "Random seed(s) shared by baseline and ML runs. "
            "Pass one value for a single run (e.g. --seed 42) or several for multi-seed runs (e.g. --seed 7 42 123). "
            "If omitted, prompts interactively."
        ),
    )
    parser.add_argument(
        "--output-root",
        default=".",
        help=(
            "Parent directory where FINAL_OUTPUT_<scenario>_seed<N>_<timestamp> is created. "
            "Do not point this to FINAL_OUTPUT_#1; the runner will create new outputs next to that archive folder."
        ),
    )
    parser.add_argument("--model-dir", default=DEFAULT_MODEL_DIR, help="Path to the trained SLA-risk GBDT model directory.")
    parser.add_argument("--controller-preset", default=DEFAULT_CONTROLLER_PRESET, help="ML controller preset.")
    parser.add_argument("--broker-preset", default=DEFAULT_BROKER_PRESET, help="Forecasting broker preset.")
    parser.add_argument(
        "--keep-raw",
        action="store_true",
        help="Keep the temporary raw comparison folder under logs/raw_runs.",
    )
    return parser


def main() -> None:
    args = build_parser().parse_args()
    repo_root = _repo_root()
    scenario = _select_scenario(args.scenario)
    scenario_config = SCENARIOS[scenario]
    seeds = _select_seeds(args.seed)
    multi_seed = len(seeds) > 1

    output_root = _resolve_output_root(args.output_root, repo_root)

    raw_root = output_root / "logs" / "raw_runs"
    completed_dirs: list[Path] = []
    for seed in seeds:
        timestamp = _timestamp()
        output_dir = output_root / f"FINAL_OUTPUT_{scenario}_seed{seed}_{timestamp}"
        raw_dir = raw_root / f"raw_{scenario}_seed{seed}_{timestamp}"
        raw_dir.mkdir(parents=True, exist_ok=False)

        command = [
            sys.executable,
            str(repo_root / "compare_baseline_vs_ml.py"),
            "--config",
            str(repo_root / scenario_config["config"]),
            "--sla-path",
            str(repo_root / scenario_config["sla"]),
            "--model-dir",
            str(repo_root / args.model_dir),
            "--controller-type",
            "gbdt",
            "--controller-preset",
            args.controller_preset,
            "--use-broker",
            "--broker-preset",
            args.broker_preset,
            "--seed",
            str(seed),
            "--output-dir",
            str(raw_dir),
            "--pipeline-output-root",
            "",
        ]

        if multi_seed:
            print(f"\n=== Seed {seed} ({seeds.index(seed) + 1}/{len(seeds)}) ===")
        print(f"Running scenario: {scenario} (seed={seed})")
        print(f"Output folder: {output_dir}")
        subprocess.run(command, cwd=repo_root, check=True)
        _copy_map_shortcuts(raw_dir)
        _generate_sla_hit_outputs(raw_dir, scenario)
        organize_pipeline_outputs(
            scenario=f"{scenario}_seed{seed}",
            comparison_dir=raw_dir,
            model_dir=repo_root / args.model_dir,
            output_dir=output_dir,
            overwrite=True,
        )
        _write_run_summary(output_dir, f"{scenario} seed {seed}", command)
        if not args.keep_raw:
            shutil.rmtree(raw_dir)
        completed_dirs.append(output_dir)

    print("\nExperiment completed.")
    if multi_seed:
        print(f"Ran {len(seeds)} seeds: {seeds}")
        for d in completed_dirs:
            print(f"  {d}")
    else:
        print(f"Final output: {completed_dirs[0]}")


if __name__ == "__main__":
    main()
